import Foundation

/// 小红书文案风格
enum WritingStyle: String, CaseIterable, Codable {
    /// 种草风 — 亲身体验、好物推荐、生活化
    case种草 = "种草风"
    /// 干货风 — 知识科普、教程指南、数据支撑
    case干货 = "干货风"
    /// 情绪风 — 情感共鸣、故事分享、走心
    case情绪 = "情绪风"
    /// 测评风 — 对比评测、优缺点、客观
    case测评 = "测评风"
    
    var promptInstruction: String {
        switch self {
        case .种草:
            return """
            你是一个小红书种草博主。请用以下风格写文案：
            - 开头：亲身体验、真实感受引入
            - 中间：产品/服务的亮点、实际使用场景
            - 结尾：种草推荐、购买建议
            - 语气：亲切、真实、有说服力
            - 长度：150-300字
            - 包含3-5个相关话题标签（#开头）
            """
        case .干货:
            return """
            你是一个小红书知识博主。请用以下风格写文案：
            - 开头：抛出问题/痛点
            - 中间：系统讲解知识/方法/步骤
            - 结尾：总结提升、行动建议
            - 语气：专业、清晰、有用
            - 长度：200-400字
            - 包含3-5个相关话题标签（#开头）
            """
        case .情绪:
            return """
            你是一个小红书情感博主。请用以下风格写文案：
            - 开头：故事/场景代入
            - 中间：情感共鸣、真实经历
            - 结尾：感悟升华、温暖收尾
            - 语气：走心、真诚、有温度
            - 长度：150-300字
            - 包含3-5个相关话题标签（#开头）
            """
        case .测评:
            return """
            你是一个小红书测评博主。请用以下风格写文案：
            - 开头：为什么测、测评背景
            - 中间：优缺点分析、对比数据、真实使用感受
            - 结尾：总结推荐、适合人群
            - 语气：客观、专业、可信
            - 长度：200-400字
            - 包含3-5个相关话题标签（#开头）
            """
        }
    }
}
